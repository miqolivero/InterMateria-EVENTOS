import api from "./axiosConfig.js";

export const listarSolicitudes = (params) => api.get("/solicitudes", { params });
export const obtenerSolicitud = (id) => api.get(`/solicitudes/${id}`);
export const crearSolicitud = (datos) => api.post("/solicitudes", datos);
export const editarSolicitud = (id, datos) => api.put(`/solicitudes/${id}`, datos);
export const cambiarEstadoSolicitud = (id, estado) => api.patch(`/solicitudes/${id}/estado`, { estado });
export const crearPresupuesto = (id, datos = {}) => api.post(`/solicitudes/${id}/presupuestos`, datos);
