export const agregarRenglon = (id, datos) => api.post(`/presupuestos/${id}/detalle`, datos);
export const editarRenglon = (id, detalle, datos) => api.put(`/presupuestos/${id}/detalle/${detalle}`, datos);
export const quitarRenglon = (id, detalle) => api.delete(`/presupuestos/${id}/detalle/${detalle}`);
export const presentarPresupuesto = (id) => api.patch(`/presupuestos/${id}/presentar`);
export const rechazarPresupuesto = (id) => api.patch(`/presupuestos/${id}/rechazar`);
export const versionarPresupuesto = (id) => api.post(`/presupuestos/${id}/nueva-version`);
export const aceptarPresupuesto = (id, datos) => api.post(`/presupuestos/${id}/aceptar`, datos);
export const listarEventos = (params) => api.get("/eventos", { params });
export const obtenerEvento = (id) => api.get(`/eventos/${id}`);
